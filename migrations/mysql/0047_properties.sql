-- The twin of migrations/sqlite/0047_properties.sql; the column notes are
-- there. Long text (descriptions, the gallery, floor plans, open houses,
-- messages, notes, a bio) is MEDIUMTEXT, nullable because MEDIUMTEXT cannot
-- take a DEFAULT; the repo reads those columns through COALESCE. Booleans
-- are SMALLINT and dates VARCHAR, as everywhere in this schema.

CREATE TABLE IF NOT EXISTS property_types (
  id          VARCHAR(24) PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  slug        VARCHAR(120) NOT NULL UNIQUE,
  description VARCHAR(600) NOT NULL DEFAULT '',
  image       VARCHAR(500) NOT NULL DEFAULT '',
  tint        VARCHAR(20) NOT NULL DEFAULT 'blue',
  sort_order  INT NOT NULL DEFAULT 0,
  created_at  VARCHAR(32) NOT NULL,
  updated_at  VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS property_agents (
  id          VARCHAR(24) PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  slug        VARCHAR(120) NOT NULL UNIQUE,
  title       VARCHAR(120) NOT NULL DEFAULT '',
  agency      VARCHAR(120) NOT NULL DEFAULT '',
  email       VARCHAR(191) NOT NULL DEFAULT '',
  phone       VARCHAR(40) NOT NULL DEFAULT '',
  mobile      VARCHAR(40) NOT NULL DEFAULT '',
  photo       VARCHAR(500) NOT NULL DEFAULT '',
  bio         MEDIUMTEXT NULL,
  website     VARCHAR(500) NOT NULL DEFAULT '',
  license     VARCHAR(60) NOT NULL DEFAULT '',
  languages   VARCHAR(120) NOT NULL DEFAULT '',
  status      VARCHAR(20) NOT NULL DEFAULT 'active',
  sort_order  INT NOT NULL DEFAULT 0,
  created_at  VARCHAR(32) NOT NULL,
  updated_at  VARCHAR(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS properties (
  id                   VARCHAR(24) PRIMARY KEY,
  slug                 VARCHAR(191) NOT NULL UNIQUE,
  title                VARCHAR(200) NOT NULL,
  status               VARCHAR(20) NOT NULL DEFAULT 'draft',
  purpose              VARCHAR(10) NOT NULL DEFAULT 'sale',
  market               VARCHAR(20) NOT NULL DEFAULT 'available',
  type_id              VARCHAR(24) NULL,
  agent_id             VARCHAR(24) NULL,
  reference            VARCHAR(40) NOT NULL DEFAULT '',
  price_cents          BIGINT NOT NULL DEFAULT 0,
  price_poa            SMALLINT NOT NULL DEFAULT 0,
  price_prefix         VARCHAR(40) NOT NULL DEFAULT '',
  rent_period          VARCHAR(10) NOT NULL DEFAULT '',
  deposit_cents        BIGINT NOT NULL DEFAULT 0,
  service_charge_cents BIGINT NOT NULL DEFAULT 0,
  tax_cents            BIGINT NOT NULL DEFAULT 0,
  summary              VARCHAR(300) NOT NULL DEFAULT '',
  description          MEDIUMTEXT NULL,
  description_lexical  MEDIUMTEXT NULL,
  description_html     MEDIUMTEXT NULL,
  image                VARCHAR(500) NOT NULL DEFAULT '',
  gallery              MEDIUMTEXT NULL,
  bedrooms             INT NOT NULL DEFAULT 0,
  bathrooms            INT NOT NULL DEFAULT 0,
  half_baths           INT NOT NULL DEFAULT 0,
  rooms                INT NOT NULL DEFAULT 0,
  parking              INT NOT NULL DEFAULT 0,
  area                 BIGINT NOT NULL DEFAULT 0,
  lot_area             BIGINT NOT NULL DEFAULT 0,
  year_built           INT NOT NULL DEFAULT 0,
  floors               INT NOT NULL DEFAULT 0,
  energy_rating        VARCHAR(10) NOT NULL DEFAULT '',
  available_from       VARCHAR(12) NOT NULL DEFAULT '',
  address              VARCHAR(200) NOT NULL DEFAULT '',
  neighborhood         VARCHAR(80) NOT NULL DEFAULT '',
  city                 VARCHAR(80) NOT NULL DEFAULT '',
  region               VARCHAR(80) NOT NULL DEFAULT '',
  postal_code          VARCHAR(20) NOT NULL DEFAULT '',
  country              VARCHAR(60) NOT NULL DEFAULT '',
  latitude             VARCHAR(20) NOT NULL DEFAULT '',
  longitude            VARCHAR(20) NOT NULL DEFAULT '',
  hide_address         SMALLINT NOT NULL DEFAULT 0,
  features             VARCHAR(600) NOT NULL DEFAULT '',
  extra_features       MEDIUMTEXT NULL,
  floor_plans          MEDIUMTEXT NULL,
  open_houses          MEDIUMTEXT NULL,
  video_url            VARCHAR(500) NOT NULL DEFAULT '',
  tour_url             VARCHAR(500) NOT NULL DEFAULT '',
  brochure_url         VARCHAR(500) NOT NULL DEFAULT '',
  featured             SMALLINT NOT NULL DEFAULT 0,
  keywords             VARCHAR(200) NOT NULL DEFAULT '',
  seo_title            VARCHAR(80) NOT NULL DEFAULT '',
  seo_description      VARCHAR(320) NOT NULL DEFAULT '',
  views                BIGINT NOT NULL DEFAULT 0,
  enquiries            BIGINT NOT NULL DEFAULT 0,
  published_at         VARCHAR(32) NULL,
  closed_at            VARCHAR(32) NULL,
  created_at           VARCHAR(32) NOT NULL,
  updated_at           VARCHAR(32) NOT NULL,
  INDEX properties_status_idx (status, purpose, market),
  INDEX properties_type_idx (type_id),
  INDEX properties_agent_idx (agent_id),
  INDEX properties_city_idx (city),
  INDEX properties_price_idx (price_cents)
);

CREATE TABLE IF NOT EXISTS property_enquiries (
  id             VARCHAR(24) PRIMARY KEY,
  property_id    VARCHAR(24) NULL,
  agent_id       VARCHAR(24) NULL,
  kind           VARCHAR(10) NOT NULL DEFAULT 'info',
  status         VARCHAR(20) NOT NULL DEFAULT 'new',
  name           VARCHAR(120) NOT NULL,
  email          VARCHAR(191) NOT NULL,
  phone          VARCHAR(40) NOT NULL DEFAULT '',
  message        MEDIUMTEXT NULL,
  preferred_date VARCHAR(12) NOT NULL DEFAULT '',
  preferred_time VARCHAR(12) NOT NULL DEFAULT '',
  note           MEDIUMTEXT NULL,
  created_at     VARCHAR(32) NOT NULL,
  updated_at     VARCHAR(32) NOT NULL,
  INDEX property_enquiries_status_idx (status, created_at),
  INDEX property_enquiries_property_idx (property_id),
  INDEX property_enquiries_email_idx (email)
);

