/// A network's mark: a monogram in a circle, brand-neutral; mail, globe,
/// link and RSS use the general icons.
pub fn social_svg(net: &str) -> String {
    match net {
        "email" => return icon_svg("mail").unwrap_or_default(),
        "website" => return icon_svg("globe").unwrap_or_default(),
        "copy" => return icon_svg("link").unwrap_or_default(),
        "rss" => return icon_svg("rss").unwrap_or_default(),
        _ => {}
    }
    let letter = match net {
        "x" => "X",
        "facebook" => "f",
        "instagram" => "Ig",
        "linkedin" => "in",
        "youtube" => "▶",
        "tiktok" => "♪",
        "github" => "gh",
        "mastodon" => "M",
        "threads" => "@",
        "bluesky" => "bs",
        "pinterest" => "P",
        "reddit" => "r",
        "whatsapp" => "W",
        "telegram" => "➤",
        "discord" => "D",
        _ => "•",
    };
    format!(
        r##"<svg viewBox="0 0 24 24" width="1em" height="1em" aria-hidden="true"><circle cx="12" cy="12" r="11" fill="currentColor"/><text x="12" y="16.2" text-anchor="middle" font-size="{fs}" font-weight="700" font-family="system-ui,sans-serif" fill="#fff">{letter}</text></svg>"##,
        fs = if letter.chars().count() > 1 { 9 } else { 12 },
    )
}
